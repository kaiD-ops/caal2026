#!/usr/bin/env python3
"""
Member 1 Validation Helper - Compare Assembly Outputs with Reference

Usage:
    python3 validate_layers.py --layer hilbert --asm-output output.bin
    python3 validate_layers.py --layer linear --asm-output output.bin
    python3 validate_layers.py --all

This script loads reference outputs generated by generate_validation_data.py
and compares them with actual assembly outputs from VeeR-iSS.
"""

import numpy as np
import argparse
from pathlib import Path
import sys


def compute_metrics(reference, actual):
    """Compute MSE, MAE, max absolute error."""
    diff = reference - actual
    mse = np.mean(diff ** 2)
    mae = np.mean(np.abs(diff))
    max_ae = np.max(np.abs(diff))
    return mse, mae, max_ae


def validate_hilbert(asm_output_file):
    """Validate Hilbert Scan layer."""
    print("\n" + "="*70)
    print("VALIDATING: Hilbert Scan")
    print("="*70)
    
    ref_file = "validation_data/hilbert_output_ref.npy"
    
    # Load reference
    if not Path(ref_file).exists():
        print(f"✗ Reference file not found: {ref_file}")
        return False
    
    reference = np.load(ref_file)
    print(f"✓ Loaded reference: shape {reference.shape}, dtype {reference.dtype}")
    
    # Load assembly output
    if not Path(asm_output_file).exists():
        print(f"✗ Assembly output file not found: {asm_output_file}")
        return False
    
    # Assume binary float32 format
    actual = np.fromfile(asm_output_file, dtype=np.float32)
    actual = actual.reshape(reference.shape)
    print(f"✓ Loaded assembly output: shape {actual.shape}, dtype {actual.dtype}")
    
    # Compute metrics
    mse, mae, max_ae = compute_metrics(reference, actual)
    
    # Threshold: MSE < 1e-12 (exact match expected)
    threshold = 1e-12
    passed = mse < threshold
    
    print(f"\nMetrics:")
    print(f"  MSE: {mse:.2e} (threshold: {threshold:.2e})")
    print(f"  MAE: {mae:.2e}")
    print(f"  Max Absolute Error: {max_ae:.2e}")
    print(f"\nResult: {'✓ PASS' if passed else '✗ FAIL'}")
    
    return passed


